export interface ColTraitsBase<
  VN extends ValueName = ValueName,
> extends ColTraitsLiteral {
  valueName: VN;
  customDefaultValue: Value<VN> | null;
}
function makeColTraits<VN extends ValueName>(
  columnId: string,
  valueName: VN,
  header: string,
  isFormula: boolean,
  emptyAllowed: boolean = false,
  customDefaultValue: Value<VN> | null = null,
): ColTraitsBase<VN> {
  return {
    columnId,
    valueName,
    header,
    isFormula,
    emptyAllowed,
    customDefaultValue,
  };
}

