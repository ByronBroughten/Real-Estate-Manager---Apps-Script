export type AllColTraits = typeof allColTraits;

export type ColumnName<SN extends SheetNameSimple = SheetNameSimple> =
  keyof AllColTraits[SN];

export type TableColTraits<SN extends SheetNameSimple> = AllColTraits[SN];

export type ColumnValueName<
  SN extends SheetNameSimple,
  CN extends ColumnName<SN>,
> = AllColTraits[SN][CN]["valueName" & keyof AllColTraits[SN][CN]];

export type ColTraits<
  SN extends SheetNameSimple,
  CN extends ColumnName<SN>,
> = ColTraitsBase<ColumnValueName<SN, CN> & ValueName>;

export type ColumnValueSchema<
  SN extends SheetNameSimple,
  CN extends ColumnName<SN>,
> = ValueSchema<ColumnValueName<SN, CN> & ValueName>;

export type ColumnValue<
  SN extends SheetNameSimple,
  CN extends ColumnName<SN>,
> = Value<ColumnValueName<SN, CN> & ValueName>;

export type SheetDataValues<
  SN extends SheetNameSimple,
  VNS extends ColumnName<SN> = ColumnName<SN>,
> = {
  [CN in VNS]: ColumnValue<SN, CN>;
};

export function getSheetColumnNames<SN extends SheetNameSimple>(
  sheetName: SN,
): ColumnName<SN>[] {
  return Obj.keys(allColTraits[sheetName]);
}

// columnConfig isn't actually very unique. The only unique
export function getColumnTraitByName<
  TN extends SheetNameSimple,
  CN extends ColumnName<TN>,
  K extends keyof ColTraits<TN, CN>,
>(sheetName: TN, columnName: CN, key: K): ColTraits<TN, CN>[K] {
  return (allColTraits[sheetName][columnName] as ColTraits<TN, CN>)[key];
}

export type IndexedColIdTraits = KeyedMap<
  Record<string, ColTraitsBase>,
  "columnId",
  "columnName"
>;

type AllColTraitsGidColId = Map<number, IndexedColIdTraits>;
function makeAllColTraitsGidColId(): AllColTraitsGidColId {
  return schemaSheetNames.reduce((attrs, sheetName) => {
    const sheetGid = getSheetTraitByName(sheetName, "sheetGid");
    attrs.set(
      sheetGid,
      Obj.toKeyedMap(allColTraits[sheetName], "columnId", "columnName"),
    );
    return attrs;
  }, new Map() as AllColTraitsGidColId);
}

const allColTraitsGidColId = makeAllColTraitsGidColId();

export type ColTraitsRaw =
  IndexedColIdTraits extends Map<any, infer V> ? V : never;
export type ColTraitsRawKey = keyof ColTraitsRaw;
export function getColumnTraitByIndex<K extends ColTraitsRawKey>(
  sheetId: number,
  columnId: string,
  key: K,
): ColTraitsRaw[K] {
  const colTraits = valS.assert(
    allColTraitsGidColId.get(sheetId)?.get(columnId),
    `column attributes for sheetId=${sheetId}, columnId=${columnId}`,
  );
  return colTraits[key];
}
export function getSheetColumnIds(sheetGid: number): MapIterator<string> {
  return valS
    .assert(
      allColTraitsGidColId.get(sheetGid),
      `column attributes for sheetId=${sheetGid}`,
    )
    .keys();
}

